"""Run every benchmark and write docs/benchmarks.md.

    cd server && python -m benchmarks.run_all [--labelled-dir DIR] [--media-dir DIR] [--quick]
"""

from __future__ import annotations

import argparse
import datetime as dt
import time
from pathlib import Path

from cloudstore.erasure.backends import get_backend

from . import bench_cache, bench_cdc, bench_erasure, bench_phash, bench_store, bench_sync
from .common import machine


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--labelled-dir", type=Path)
    ap.add_argument("--media-dir", type=Path)
    ap.add_argument("--quick", action="store_true")
    ap.add_argument("--out", type=Path, default=Path(__file__).resolve().parents[2] / "docs" / "benchmarks.md")
    args = ap.parse_args()

    t0 = time.time()
    parts = [
        "# Benchmarks",
        "",
        f"Generated by `python -m benchmarks.run_all` on **{machine()}** "
        f"({dt.date.today().isoformat()}), GF backend `{get_backend().name}`. "
        "Virtual disks are directories on the laptop SSD, so absolute store numbers are an upper bound for a "
        "mini PC with USB HDDs; the algorithmic comparisons (ratios, scaling) carry over. Re-run on the "
        "deployment machine for its own numbers.",
    ]

    def section(title: str, body: str) -> None:
        print(f"== {title}")
        parts.extend(["", f"## {title}", "", body])

    enc_md, enc = bench_erasure.encode_throughput()
    speed = enc.get("simd_speedup")
    section("1. Reed–Solomon encode throughput",
            enc_md + (f"\n\nSIMD split-nibble kernel vs scalar table kernel (same C code, one region multiply): "
                      f"**{speed:.1f}× faster**." if speed else ""))
    rec_md, _ = bench_erasure.reconstruct()
    section("2. Reconstruction and disk rebuild", rec_md)
    section("3. Usable capacity vs mirroring", bench_erasure.capacity())
    section("3b. Decode-matrix inversion cost", bench_erasure.cost_matrix_inversion())
    section("4. Object store: healthy vs degraded reads, rebuild under load",
            bench_store.run(n_objects=20 if args.quick else 60))
    items = bench_phash.load_labelled_dir(args.labelled_dir) if args.labelled_dir else bench_phash.labelled_set(
        30 if args.quick else 60)
    acc_md, best = bench_phash.accuracy(items)
    src = f"real labelled set `{args.labelled_dir}`" if args.labelled_dir else (
        "procedurally generated labelled set (base scene + 3 random edits per group, from: "
        + ", ".join(bench_phash.EDITS) + ")")
    summary = "; ".join(f"{k} best F1 {v[1]:.3f} at r={v[0]} (P={v[2]:.3f}, R={v[3]:.3f})" for k, v in best.items())
    section("5. Near-duplicate detection accuracy",
            f"{len(items)} images, {src}.\n\n{acc_md}\n\n**{summary}.** The production radius is "
            f"`CLOUDSTORE_DUP_RADIUS` (default 10 on pHash). Synthetic scenes are easier than real bursts; run with "
            f"`--labelled-dir` on a hand-labelled folder of real photos to tune the radius for your library.")
    section("5b. Near-duplicate query latency", bench_phash.speed(queries=100 if args.quick else 300))
    section("6. Merkle sync vs full manifest", bench_sync.run())
    cdc_md, _ = bench_cdc.run(args.media_dir)
    section("7. Content-defined chunking: media vs non-media (honest numbers)", cdc_md)
    section("8. Thumbnail cache", bench_cache.run())
    parts += ["", f"_Total benchmark time: {time.time() - t0:.0f} s._", ""]
    args.out.write_text("\n".join(parts))
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
